"""Render data/inventory.md from the download manifest, Kaggle metadata and cleaning tallies.

    python -m data.transforms.run && python -m data.build_inventory
"""
from __future__ import annotations

import json
from datetime import date

from data.transforms.common import PROCESSED, RAW, REPO

SOURCES = [
    # key, folder, kaggle slug, pack name, processed table, what it is used for
    ("no_shows", "no_shows", "joniarroba/noshowappointments", "Medical Appointment No Shows",
     "src_appointment_history", "Scheduling history and the no-show signal behind slot logic"),
    ("disease_symptom", "disease_symptom", "itachi9604/disease-symptom-description-dataset", "Disease Symptom Prediction",
     "src_condition_symptom", "Symptom-to-condition signal behind the specialty match"),
    ("transcriptions", "transcriptions", "tboyle10/medicaltranscriptions", "Medical Transcriptions",
     "src_transcription_note", "Seed text for synthetic report PDFs and dictations"),
    ("az_medicine", "az_medicine", "shudhanshusingh/az-medicine-dataset-of-india", "A-Z Medicine Dataset of India",
     "medicine", "Formulary for stock checks and substitutes"),
    ("healthcare", "healthcare", "prasad22/healthcare-dataset", "Healthcare Dataset (synthetic)",
     "src_encounter_history", "Patient master and encounter history"),
]


def licence(folder: str) -> str:
    meta = RAW / folder / "_meta" / "dataset-metadata.json"
    if not meta.exists():
        return "not recorded — run `METADATA_ONLY=1 bash data/fetch_datasets.sh`"
    data = json.loads(meta.read_text())
    data = data.get("info", data)  # `kaggle datasets metadata` nests the fields under "info"
    names = [l.get("name") or l.get("nameNullable") for l in data.get("licenses", []) if isinstance(l, dict)]
    return ", ".join(n for n in names if n) or "not stated by the publisher"


def checksums() -> dict[str, list[tuple[str, str]]]:
    out: dict[str, list[tuple[str, str]]] = {}
    for line in (RAW / "MANIFEST.sha256").read_text().splitlines():
        digest, path = line.split(maxsplit=1)
        folder = path.lstrip("./").split("/")[0]
        out.setdefault(folder, []).append((path.lstrip("./"), digest))
    return out


def main() -> None:
    report = json.loads((PROCESSED / "report.json").read_text())
    sums = checksums()
    lines = [
        "# Data inventory",
        "",
        f"Generated by `python -m data.build_inventory` on {date.today().isoformat()}. "
        "Raw files live in `data/raw/` (git-ignored) and are fetched with `bash data/fetch_datasets.sh`.",
        "",
        "## Sources",
        "",
        "| Source | Kaggle | Licence | Rows in | Rows out | Loaded into | Used for |",
        "|---|---|---|---|---|---|---|",
    ]
    for key, folder, slug, name, table, use in SOURCES:
        r = report[key]
        lines.append(f"| {name} | [`{slug}`](https://www.kaggle.com/datasets/{slug}) | {licence(folder)} | "
                     f"{r['rows_in']:,} | {r['rows_out']:,} | `{table}` | {use} |")
    lines += ["", "Medical Appointment No Shows is also published on OpenML as dataset 43439 (CC BY-NC-SA 4.0 per the pack). "
              "A non-commercial licence is acceptable for this engagement and would be flagged to procurement at a real client.",
              "", "## Cleaning tally", "",
              "Every dropped row has a reason; rows in minus dropped equals rows out for every source.", ""]
    for key, _, _, name, _, _ in SOURCES:
        r = report[key]
        dropped = "; ".join(f"{k}: {v:,}" for k, v in r["dropped"].items()) or "none"
        lines.append(f"- **{name}** — dropped: {dropped}. {' '.join(n + '.' for n in r['notes'])}")
    lines += ["", "## Files and checksums (SHA-256)", "", "| File | SHA-256 |", "|---|---|"]
    for folder in sorted(sums):
        for path, digest in sums[folder]:
            lines.append(f"| `{path}` | `{digest[:16]}…` |")
    lines += ["", "## Reference data written by the team", "",
              "| File | Rows | What it is |", "|---|---|---|",
              "| `data/reference/sites.csv` | 28 | 6 hospitals and 22 clinics across Pune and Hyderabad (p3); fictional |",
              "| `data/reference/specialties.csv` | 33 | Network specialties, derived from the transcription labels and the crosswalk |",
              "| `data/reference/condition_specialty_crosswalk.csv` | 41 | Condition to specialty; drafted by the AI assistant, each row needs a reviewer mark |",
              ""]
    (REPO / "data" / "inventory.md").write_text("\n".join(lines))
    print("wrote data/inventory.md")


if __name__ == "__main__":
    main()
